"""Scenario files: what a simulated Splunk instance contains.

One YAML file per scenario under ``simulator/scenarios/``. A scenario declares indexes and sourcetypes with
seeded event generators, saved searches (full config), scheduler history and faults. Nothing here touches the
network. Events are generated by ``simulator.engine`` relative to an injectable "now".
"""

from __future__ import annotations

import re
from datetime import timedelta
from pathlib import Path
from typing import Any, Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from logops.gateway.base import GATEWAY_OPS
from logops.models import SavedSearch

SCENARIO_DIR = Path(__file__).parent / "scenarios"

_DURATION_RE = re.compile(r"^(\d+)\s*(s|m|h|d|w)$")
_UNIT_SECONDS = {"s": 1, "m": 60, "h": 3600, "d": 86400, "w": 604800}


def parse_duration(text: str) -> timedelta:
    """``"15m"`` → 15 minutes. Units: s, m, h, d, w."""
    m = _DURATION_RE.match(text.strip())
    if not m:
        raise ValueError(f"invalid duration {text!r} (expected e.g. 30s, 15m, 24h, 7d, 1w)")
    return timedelta(seconds=int(m.group(1)) * _UNIT_SECONDS[m.group(2)])


class _Spec(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


Scalar = str | int | float | bool


class FieldGen(_Spec):
    """How one event field is generated. Exactly one of the options must be set."""

    value: Scalar | None = None
    choices: tuple[Scalar, ...] | None = None
    ip_prefix: str | None = None
    """``"10.0"`` produces ``10.0.<1-255>.<1-255>``."""
    int_range: tuple[int, int] | None = None

    @model_validator(mode="after")
    def _exactly_one(self) -> FieldGen:
        set_ = [n for n in ("value", "choices", "ip_prefix", "int_range") if getattr(self, n) is not None]
        if len(set_) != 1:
            raise ValueError(
                f"field generator needs exactly one of value/choices/ip_prefix/int_range, got {set_}"
            )
        if self.choices is not None and not self.choices:
            raise ValueError("choices must not be empty")
        return self


class SourcetypeSpec(_Spec):
    name: str
    generator: Literal["security", "database", "custom"]
    """``security`` and ``database`` reproduce the v1 ``log_generator.py`` event shapes."""
    count: int = Field(ge=0, le=100_000)
    span: str = "24h"
    """Events are spread evenly over ``[now - span, now - lag]``."""
    lag: str = "1m"
    """Age of the newest event. A large lag models stopped ingestion."""
    host: str = "sim-host-01"
    source: str | None = None
    fields: dict[str, FieldGen] = Field(default_factory=dict)
    """Extra fields (``custom``) or overrides of the built-in shape."""
    rename_fields: dict[str, str] = Field(default_factory=dict)
    """Schema drift, e.g. ``{src_ip: source_ip}``."""
    drop_fields: tuple[str, ...] = ()

    @field_validator("span", "lag")
    @classmethod
    def _duration(cls, v: str) -> str:
        parse_duration(v)
        return v

    @model_validator(mode="after")
    def _window(self) -> SourcetypeSpec:
        if parse_duration(self.lag) > parse_duration(self.span):
            raise ValueError(f"sourcetype {self.name!r}: lag must not exceed span")
        return self


class IndexSpec(_Spec):
    name: str
    sourcetypes: tuple[SourcetypeSpec, ...] = ()


class SchedulerSpec(_Spec):
    """A regular series of scheduler runs, newest first: ``now - offset - k * every`` for k < count."""

    rule_name: str
    every: str = "15m"
    count: int = Field(ge=0, le=10_000)
    offset: str = "0s"
    status: str = "success"
    result_count: int | None = 0
    message: str | None = None

    @field_validator("every", "offset")
    @classmethod
    def _duration(cls, v: str) -> str:
        parse_duration(v)
        return v


OpSelector = bool | tuple[str, ...]


class FaultSpec(_Spec):
    """Faults injected by the simulator server. Each selector is ``true`` (every op) or a list of op names."""

    unavailable: OpSelector = False
    """The op answers with a structured ``unavailable`` error (gateway: ``ConnectError``)."""
    auth_denied: OpSelector = False
    """The op answers with a structured ``auth`` error (gateway: ``AuthError``)."""
    timeout_ms: int | None = Field(default=None, ge=1, le=600_000)
    """Delay before answering. Combined with a shorter client timeout this gives ``IntegrationTimeout``."""
    timeout_ops: OpSelector = True
    malformed: OpSelector = False
    """The op answers with a payload that does not match the contract (gateway: ``BadResponse``)."""

    @field_validator("unavailable", "auth_denied", "timeout_ops", "malformed")
    @classmethod
    def _known_ops(cls, v: OpSelector) -> OpSelector:
        if isinstance(v, tuple):
            unknown = sorted(set(v) - set(GATEWAY_OPS))
            if unknown:
                raise ValueError(f"unknown ops in fault selector: {unknown}")
        return v

    @staticmethod
    def selects(selector: OpSelector, op: str) -> bool:
        return selector is True or (isinstance(selector, tuple) and op in selector)

    def fault_for(self, op: str) -> str | None:
        """The error fault (``unavailable``/``auth``/``malformed``) that applies to ``op``, if any."""
        if self.selects(self.unavailable, op):
            return "unavailable"
        if self.selects(self.auth_denied, op):
            return "auth"
        if self.selects(self.malformed, op):
            return "malformed"
        return None

    def delay_for(self, op: str) -> float:
        if self.timeout_ms is None or not self.selects(self.timeout_ops, op):
            return 0.0
        return self.timeout_ms / 1000.0


class Scenario(_Spec):
    name: str
    description: str = ""
    seed: int = 1
    indexes: tuple[IndexSpec, ...] = ()
    saved_searches: tuple[SavedSearch, ...] = ()
    scheduler: tuple[SchedulerSpec, ...] = ()
    faults: FaultSpec = FaultSpec()
    expected: dict[str, str] = Field(default_factory=dict)
    """Rule name → expected ``HealthStatus`` (the ROADMAP acceptance table). Documentation for audit tests."""
    detection_tests: tuple[dict[str, Any], ...] = ()
    """Raw detection test cases. Phase 5 defines their schema; the simulator does not interpret them yet."""

    @model_validator(mode="after")
    def _unique(self) -> Scenario:
        names = [i.name for i in self.indexes]
        if len(names) != len(set(names)):
            raise ValueError("duplicate index names")
        rules = [s.name for s in self.saved_searches]
        if len(rules) != len(set(rules)):
            raise ValueError("duplicate saved search names")
        return self


def available_scenarios() -> list[str]:
    return sorted(p.stem for p in SCENARIO_DIR.glob("*.yaml"))


def load_scenario(name_or_path: str | Path) -> Scenario:
    """Load a scenario by name (``healthy``) or by path to a YAML file."""
    path = Path(name_or_path)
    if path.suffix not in (".yaml", ".yml"):
        if not re.fullmatch(r"[A-Za-z0-9_\-]+", str(name_or_path)):
            raise ValueError(f"invalid scenario name {name_or_path!r}")
        path = SCENARIO_DIR / f"{name_or_path}.yaml"
    if not path.is_file():
        raise FileNotFoundError(f"scenario not found: {name_or_path!r} (available: {available_scenarios()})")
    with path.open(encoding="utf-8") as fh:
        data = yaml.safe_load(fh)
    if not isinstance(data, dict):
        raise ValueError(f"scenario {path.name} must be a YAML mapping")
    return Scenario.model_validate(data)
